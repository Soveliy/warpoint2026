export const defaultLocationState = {
  cityName: 'Екатеринбург',
  countryId: 'ru',
  locationId: 'veer-mall',
};

export function getCountry(countryId) {
  return countries.find((country) => country.id === countryId) ?? countries[0];
}

export function getLocations(countryId, cityName) {
  if (countryId === 'ru' && cityName === 'Екатеринбург') {
    return ekaterinburgLocations;
  }

  const country = getCountry(countryId);
  const cityIndex = Math.max(country.cities.indexOf(cityName), 0);

  return [
    {
      id: `${country.id}-${cityIndex}`,
      name: `Warpoint ${cityName}`,
      address: cityName,
      details: 'Адрес клуба уточняется',
      headerAddress: cityName,
      image: 'img/zones/1.jpg',
      rating: '5.0',
      type: 'Парк',
    },
  ];
}

export function getLocation(state) {
  return getLocations(state.countryId, state.cityName).find(
    (location) => location.id === state.locationId,
  );
}
